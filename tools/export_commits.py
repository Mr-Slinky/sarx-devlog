"""Exports the commits of one month of Sarx into a script that the month's logbook page loads.

The logbook shows each day's commits on the page facing that day's entry. The site has no server,
so the commits live in one JavaScript file per month, under data/commits. This script writes that
file from the Sarx repository's git history.

Example, run from the root of this repository:

    python tools/export_commits.py 2026-11

The script reads the dev branch along its first parent only, and skips merge commits. The squash
commits on main, which repeat work already on dev, therefore stay out of the log.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_REPO = ROOT.parent / "sarx"
FIELD_SEPARATOR = "\x1f"
AGENT_AUTHOR = "Claude"


def read_commits(repo: Path, branch: str, month: str) -> list[dict]:
    """Returns every commit on the branch whose author date falls in the month, oldest first."""
    log_format = FIELD_SEPARATOR.join(["%h", "%ad", "%an", "%s"])
    command = [
        "git", "log", branch, "--first-parent", "--no-merges", "--reverse",
        "--date=short", f"--format={log_format}",
    ]
    output = subprocess.run(command, cwd=repo, capture_output=True, text=True, encoding="utf-8", check=True).stdout

    commits = []
    for line in output.splitlines():
        short_hash, date, author, subject = line.split(FIELD_SEPARATOR, 3)
        if date.startswith(month):
            commits.append({"hash": short_hash, "date": date, "author": author, "subject": subject})
    return commits


def parse_subject(subject: str) -> dict:
    """Splits a Conventional Commits subject, such as 'feat(enki): add the World', into its parts."""
    head, separator, description = subject.partition(": ")
    if not separator or " " in head:
        return {"type": "", "scope": "", "description": subject}
    kind, _, scope = head.partition("(")
    return {"type": kind, "scope": scope.rstrip(")"), "description": description}


def group_by_day(commits: list[dict]) -> dict:
    """Groups the commits under their dates, keeping the order within each day."""
    days: dict[str, list] = {}
    for commit in commits:
        entry = {"hash": commit["hash"], **parse_subject(commit["subject"])}
        if commit["author"] == AGENT_AUTHOR:
            entry["agent"] = True
        days.setdefault(commit["date"], []).append(entry)
    return days


def write_script(month: str, days: dict) -> Path:
    """Writes the month's commits as a script that registers them on window.SARX_COMMITS."""
    path = ROOT / "data" / "commits" / f"{month}.js"
    path.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(days, indent=2, ensure_ascii=False)
    script = (
        "// Generated by tools/export_commits.py from the Sarx git history. Run the script again to refresh it.\n"
        "window.SARX_COMMITS = window.SARX_COMMITS || {};\n"
        f'window.SARX_COMMITS["{month}"] = {body};\n'
    )
    path.write_text(script, encoding="utf-8")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("month", help="the month to export, as YYYY-MM")
    parser.add_argument("--repo", type=Path, default=DEFAULT_REPO, help="the Sarx repository")
    parser.add_argument("--branch", default="dev", help="the branch to read")
    args = parser.parse_args()

    commits = read_commits(args.repo, args.branch, args.month)
    days = group_by_day(commits)
    path = write_script(args.month, days)
    print(f"Wrote {len(commits)} commits over {len(days)} days to {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
